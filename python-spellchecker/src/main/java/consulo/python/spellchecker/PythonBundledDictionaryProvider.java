package consulo.python.spellchecker;

import consulo.annotation.component.ExtensionImpl;
import consulo.language.spellchecker.editor.dictionary.BundledDictionaryProvider;

import java.io.InputStream;
import java.util.function.BiConsumer;

@ExtensionImpl
public final class PythonBundledDictionaryProvider implements BundledDictionaryProvider {
    public String[] getBundledDictionaries() {
        return new String[]{
            "python.dic", // autogenerated from python stdlib
            "django.dic",

            // manually added
            "acronyms.dic",
            "logging.dic",
            "pytest.dic",
            "pythonExtras.dic",
            "sqlalchemy.dic",
            "tox.dic",
        };
    }

    @Override
    public void loadDictionaries(BiConsumer<String, InputStream> consumer) {
        for (String dictionary : getBundledDictionaries()) {
            InputStream stream = getClass().getResourceAsStream(dictionary);
            if (stream != null) {
                consumer.accept(dictionary, stream);
            }
        }
    }
}
