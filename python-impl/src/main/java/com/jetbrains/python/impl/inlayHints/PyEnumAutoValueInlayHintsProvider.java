import java.util.*;

/**
 * Shows the value generated by `enum.auto()` as an inlay hint next to the member declaration.
 * <p>
 * The value is computed statically following the semantics of `Enum._generate_next_value_`:
 * - for a plain `Enum`/`IntEnum`: the previous integer value plus one (starting from `1`);
 * - for a `Flag`/`IntFlag`: the next power of two;
 * - for a `StrEnum`: the lower-cased member name.
 * <p>
 * No hint is shown when the value cannot be determined statically (a custom `_generate_next_value_`,
 * a preceding member whose value is not a literal, etc.).
 * <p>
 * For example:
 * <pre>
 * class E(Enum):
 *     A = auto()  # = 1
 *     B = auto()  # = 2
 *     C = auto()  # = 3
 * </pre>
 */
@ExtensionImpl
public class PyEnumAutoValueInlayHintsProvider implements DeclarativeInlayHintsProvider {
    private static final String GENERATE_NEXT_VALUE = "_generate_next_value_";
    private static final String STR_ENUM = "enum.StrEnum";

    @Override
    public DeclarativeInlayHintsCollector createCollector(PsiFile file, Editor editor) {
        return new Collector();
    }

    @Override
    public Language getLanguage() {
        return PythonLanguage.INSTANCE;
    }

    @Override
    public String getId() {
        return "python.enum.auto.value.inlays";
    }

    @Override
    public LocalizeValue getName() {
        return PyLocalize.inlayEnumAutoValue();
    }

    @Override
    public LocalizeValue getDescription() {
        return PyLocalize.inlayEnumAutoValueDescription();
    }

    @Override
    public LocalizeValue getPreviewFileText() {
        // resources/inlayProviders/python.enum.auto.value.inlays/preview.py
        return LocalizeValue.of("""
            # enum.auto() value hints show the generated member value
            from enum import Enum, Flag, StrEnum, auto


            # Consecutive integers for a plain Enum
            class Priority(Enum):
                LOW = auto()/*<# = 1#>*/
                MEDIUM = 5
                HIGH = auto()/*<# = 6#>*/


            # Successive powers of two for a Flag
            class Permission(Flag):
                READ = auto()/*<# = 1#>*/
                WRITE = auto()/*<# = 2#>*/
                EXECUTE = auto()/*<# = 4#>*/


            # Lower-cased member name for a StrEnum
            class Color(StrEnum):
                RED = auto()/*<# = 'red'#>*/
                GREEN = auto()/*<# = 'green'#>*/
            """);
    }

    @Override
    public InlayGroup getGroup() {
        return InlayGroup.VALUES_GROUP;
    }

    @Override
    public boolean isEnabledByDefault() {
        return true;
    }

    private enum AutoKind {
        INT,
        FLAG,
        STR
    }

    private sealed interface MemberValue {
        /**
         * A statically known integer value.
         */
        record Int(long value) implements MemberValue {
        }

        /**
         * A statically known non-integer value (string, tuple, ...).
         */
        final class NonInt implements MemberValue {
            static final NonInt INSTANCE = new NonInt();
        }

        /**
         * A value that could not be evaluated statically.
         */
        final class Unknown implements MemberValue {
            static final Unknown INSTANCE = new Unknown();
        }
    }

    private static class Collector implements DeclarativeInlayHintsCollector.SharedBypassCollector {
        /**
         * Per-file cache: auto member -> rendered hint text, computed lazily for the whole enum class at once.
         */
        private final Map<PyClass, Map<PyTargetExpression, String>> cache = new HashMap<>();

        @Override
        public void collectFromElement(PsiElement element, DeclarativeInlayTreeSink sink) {
            if (!(element instanceof PyTargetExpression targetExpression)) {
                return;
            }
            // Cheap pre-filter: only members assigned an `auto()` call are interesting.
            if (!(targetExpression.findAssignedValue() instanceof PyCallExpression assignedValue)) {
                return;
            }
            if (!(ScopeUtil.getScopeOwner(element) instanceof PyClass enumClass)) {
                return;
            }

            String hint = cache.computeIfAbsent(enumClass, Collector::computeAutoValues).get(targetExpression);
            if (hint == null) {
                return;
            }

            sink.addPresentation(
                new DeclarativeInlayPosition.InlineInlayPosition(assignedValue.getTextRange().getEndOffset(), true),
                null,
                PyLocalize.inlayEnumAutoValueTooltip().get(),
                HintFormat.DEFAULT,
                builder -> builder.text(hint)
            );
        }

        private static Map<PyTargetExpression, String> computeAutoValues(PyClass enumClass) {
            TypeEvalContext context = TypeEvalContext.codeAnalysis(enumClass.getProject(), enumClass.getContainingFile());
            if (!PyStdlibTypeProvider.isCustomEnum(enumClass, context)) {
                return Map.of();
            }
            AutoKind kind = autoValueKind(enumClass, context);
            if (kind == null) {
                return Map.of();
            }

            Map<PyTargetExpression, String> result = new HashMap<>();
            List<MemberValue> lastValues = new ArrayList<>();

            for (PyTargetExpression attribute : enumClass.getClassAttributes()) {
                PyStdlibTypeProvider.EnumAttributeInfo info = PyStdlibTypeProvider.getEnumAttributeInfo(enumClass, attribute, context);
                if (info == null || info.attributeKind() == EnumAttributeKind.NONMEMBER) {
                    continue;
                }

                String name = attribute.getName();
                PyExpression value = attribute.findAssignedValue();

                if (name != null && isEnumAutoCall(value, context)) {
                    switch (kind) {
                        case STR -> {
                            result.put(attribute, " = '" + name.toLowerCase(Locale.ROOT) + "'");
                            lastValues.add(MemberValue.NonInt.INSTANCE);
                        }
                        case INT -> {
                            Long next = nextIntValue(lastValues);
                            if (next != null) {
                                result.put(attribute, " = " + next);
                                lastValues.add(new MemberValue.Int(next));
                            }
                            else {
                                lastValues.add(MemberValue.Unknown.INSTANCE);
                            }
                        }
                        case FLAG -> {
                            Long next = nextFlagValue(lastValues);
                            if (next != null) {
                                result.put(attribute, " = " + next);
                                lastValues.add(new MemberValue.Int(next));
                            }
                            else {
                                lastValues.add(MemberValue.Unknown.INSTANCE);
                            }
                        }
                    }
                }
                else {
                    lastValues.add(evaluate(value));
                }
            }
            return result;
        }

        private static @Nullable AutoKind autoValueKind(PyClass enumClass, TypeEvalContext context) {
            // `Flag`/`IntFlag` generate powers of two; they don't override `_generate_next_value_` in typeshed.
            if (enumClass.isSubclass(PyNames.TYPE_ENUM_FLAG, context)) {
                return AutoKind.FLAG;
            }

            PyFunction generateNextValue = enumClass.findMethodByName(GENERATE_NEXT_VALUE, true, context);
            if (generateNextValue == null) {
                return null;
            }
            PyClass containingClass = generateNextValue.getContainingClass();
            String qualifiedName = containingClass != null ? containingClass.getQualifiedName() : null;
            if (PyNames.TYPE_ENUM.equals(qualifiedName)) {
                return AutoKind.INT;
            }
            if (STR_ENUM.equals(qualifiedName)) {
                return AutoKind.STR;
            }
            return null; // a custom `_generate_next_value_`: cannot compute statically
        }

        private static boolean isEnumAutoCall(@Nullable PyExpression value, TypeEvalContext context) {
            if (!(value instanceof PyCallExpression call)) {
                return false;
            }
            if (!(call.getCallee() instanceof PyReferenceExpression callee)) {
                return false;
            }
            PyResolveContext resolveContext = PyResolveContext.defaultContext(context);
            for (ResolveResult it : callee.getReference(resolveContext).multiResolve(false)) {
                PsiElement resolved = it.getElement();
                if (resolved instanceof PyClass pyClass && PyNames.TYPE_ENUM_AUTO.equals(pyClass.getQualifiedName())) {
                    return true;
                }
            }
            return false;
        }

        /**
         * Mirrors the default `Enum._generate_next_value_`: most recent integer value plus one, or `1` to start.
         */
        private static @Nullable Long nextIntValue(List<MemberValue> lastValues) {
            for (int i = lastValues.size() - 1; i >= 0; i--) {
                MemberValue value = lastValues.get(i);
                if (value instanceof MemberValue.Int intValue) {
                    return intValue.value() + 1;
                }
                else if (value instanceof MemberValue.NonInt) {
                    continue; // non-integer values raise `TypeError` at runtime and are skipped
                }
                else if (value instanceof MemberValue.Unknown) {
                    return null; // an unevaluable value: bail to avoid showing a wrong hint
                }
            }
            return 1L;
        }

        /**
         * Mirrors `Flag._generate_next_value_`: the next power of two above the highest value seen so far.
         */
        private static @Nullable Long nextFlagValue(List<MemberValue> lastValues) {
            if (lastValues.isEmpty()) {
                return 1L;
            }
            long max = -1L;
            for (MemberValue value : lastValues) {
                if (!(value instanceof MemberValue.Int intValue)) {
                    return null;
                }
                if (intValue.value() > max) {
                    max = intValue.value();
                }
            }
            if (max < 0) {
                return null;
            }
            int bitLength = Long.SIZE - Long.numberOfLeadingZeros(max);
            if (bitLength >= Long.SIZE - 1) {
                return null; // guard against overflow for unrealistically large flags
            }
            return 1L << bitLength;
        }

        private static MemberValue evaluate(@Nullable PyExpression value) {
            PyExpression expression = PyPsiUtils.flattenParens(value);
            if (expression instanceof PyNumericLiteralExpression numericLiteral) {
                if (numericLiteral.isIntegerLiteral()) {
                    Long longValue = numericLiteral.getLongValue();
                    return longValue != null ? new MemberValue.Int(longValue) : MemberValue.Unknown.INSTANCE;
                }
                return MemberValue.NonInt.INSTANCE;
            }
            if (expression instanceof PyPrefixExpression prefixExpression) {
                if (prefixExpression.getOperator() == PyTokenTypes.MINUS) {
                    PyExpression operand = PyPsiUtils.flattenParens(prefixExpression.getOperand());
                    if (operand instanceof PyNumericLiteralExpression numericOperand && numericOperand.isIntegerLiteral()) {
                        Long longValue = numericOperand.getLongValue();
                        return longValue != null ? new MemberValue.Int(-longValue) : MemberValue.Unknown.INSTANCE;
                    }
                    return MemberValue.Unknown.INSTANCE;
                }
                return MemberValue.Unknown.INSTANCE;
            }
            if (expression instanceof PyStringLiteralExpression || expression instanceof PyTupleExpression) {
                return MemberValue.NonInt.INSTANCE;
            }
            return MemberValue.Unknown.INSTANCE;
        }
    }
}
