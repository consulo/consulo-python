package com.jetbrains.numpy.codeInsight;

import com.google.common.collect.ImmutableMap;
import com.jetbrains.python.documentation.PythonDocumentationLinkProvider;
import com.jetbrains.python.impl.documentation.PythonDocumentationMap;
import com.jetbrains.python.impl.documentation.PythonDocumentationProvider;
import consulo.annotation.component.ExtensionImpl;
import consulo.language.psi.PsiElement;
import consulo.language.psi.util.QualifiedName;
import org.jspecify.annotations.Nullable;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.Map;
import java.util.Objects;

@ExtensionImpl
public class SciPyDocumentationLinkProvider implements PythonDocumentationLinkProvider {

    // JB: `by lazy` property
    private static final class NameToWebpageNameHolder {
        private static final Map<String, String> nameToWebpageName = load();

        private static Map<String, String> load() {
            ImmutableMap.Builder<String, String> b = ImmutableMap.builder();
            try (BufferedReader inputStream = new BufferedReader(
                new InputStreamReader(
                    Objects.requireNonNull(SciPyDocumentationLinkProvider.class
                        // generated by scipy_doc_mapping.py
                        .getResourceAsStream("/com/jetbrains/numpy/codeInsight/scipyNameMapping.tsv")),
                    StandardCharsets.UTF_8
                ))) {
                inputStream.lines().forEach(line -> {
                    String[] kv = line.split("\t");
                    b.put(kv[0], kv[1]);
                });
            }
            catch (IOException e) {
                throw new RuntimeException(e);
            }

            return b.build();
        }
    }

    @Override
    public @Nullable String getExternalDocumentationUrl(PsiElement element, PsiElement originalElement) {
        QualifiedName qname = PythonDocumentationProvider.getFullQualifiedName(element);

        if (qname != null && Arrays.asList("numpy", "scipy").contains(qname.getFirstComponent()) &&
            !PythonDocumentationMap.getInstance().getEntries().containsKey(qname.getFirstComponent())) {
            String webPage = NameToWebpageNameHolder.nameToWebpageName.get(qname.toString());
            if (webPage != null) {
                if (Objects.equals(qname.getFirstComponent(), "numpy")) {
                    return "https://numpy.org/doc/stable/" + webPage;
                }
                else {
                    return "https://docs.scipy.org/doc/scipy/" + webPage;
                }
            }
            else {
                return "https://docs.scipy.org/doc/" + qname.getFirstComponent() + "/reference/";
            }
        }
        else {
            return null;
        }
    }
}
